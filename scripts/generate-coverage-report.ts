/**
 * Writes reports/coverage.json and reports/coverage.md and prints a summary.
 * Figures are computed from the data; nothing is estimated or rounded up.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { coverageReport, CRITERIA_LABELS, type CoverageCriteria } from '../src/features/content/coverage.ts';
import { buildContent } from '../src/features/content/model.ts';
import { loadRawContent, REPORTS_DIR } from './lib/load.ts';

const { content } = buildContent(loadRawContent());
const report = coverageReport(content);
const t = report.totals;
mkdirSync(REPORTS_DIR, { recursive: true });
writeFileSync(join(REPORTS_DIR, 'coverage.json'), JSON.stringify(report, null, 2) + '\n');

const tick = (v: boolean) => (v ? 'yes' : 'no');
const criteriaKeys = Object.keys(CRITERIA_LABELS) as (keyof CoverageCriteria)[];
const table = (rows: typeof report.badges) =>
  [
    `| Name | Rating | Leaves with resources | ${criteriaKeys.map((k) => CRITERIA_LABELS[k]).join(' | ')} |`,
    `|---|---|---|${criteriaKeys.map(() => '---').join('|')}|`,
    ...rows.map((r) => `| ${r.name} | ${r.rating} | ${r.leavesWithResources}/${r.leafCount} | ${criteriaKeys.map((k) => tick(r.criteria[k])).join(' | ')} |`),
  ].join('\n');

const md = `# ScoutPath content coverage

Dataset ${report.generatedFor}. Generated by \`npm run content:coverage\`.

- Merit badges listed: ${t.badgesListed} (listings unverified: ${content.badges.filter((b) => b.catalogStatus !== 'verified').length})
- Merit badges with a requirement outline: ${t.badgesWithOutline}
- Badge ratings: ${Object.entries(t.badgesByRating).map(([k, v]) => `${k} ${v}`).join(', ')}
- Ranks with a requirement outline: ${t.ranksWithOutline} of ${report.ranks.length}
- Requirements: ${t.requirements} (${t.leafRequirements} leaf requirements, ${t.leafRequirementsWithResources} with at least one resource)
- Resources: ${t.resources} (${t.resourcesLinkChecked} link-checked, ${t.resourcesContentReviewed} content-reviewed)
- Requirement–resource mappings: ${t.mappings}

## Badges with outlines

${table(report.badges.filter((b) => b.hasOutline))}

## Ranks

${table(report.ranks)}

## Requirements without resources (${report.requirementsWithoutResources.length})

${report.requirementsWithoutResources.map((r) => `- ${r.owner} ${r.number} — ${r.title} (\`${r.id}\`)`).join('\n')}

## Resources not mapped to a requirement (${report.resourcesWithoutRequirements.length})

${report.resourcesWithoutRequirements.map((r) => `- ${r.title} (\`${r.id}\`)`).join('\n') || '- None'}

## Records needing review (${report.needsReview.length})

${report.needsReview.map((r) => `- \`${r.id}\` — ${r.kind}: ${r.reason}`).join('\n')}
`;
writeFileSync(join(REPORTS_DIR, 'coverage.md'), md);

console.log(`Badges listed: ${t.badgesListed}; with outline: ${t.badgesWithOutline}; ratings: ${JSON.stringify(t.badgesByRating)}`);
console.log(`Ranks with outline: ${t.ranksWithOutline}/${report.ranks.length}`);
console.log(`Leaf requirements with resources: ${t.leafRequirementsWithResources}/${t.leafRequirements}`);
console.log(`Resources: ${t.resources} (link-checked ${t.resourcesLinkChecked}, content-reviewed ${t.resourcesContentReviewed})`);
console.log(`Records needing review: ${report.needsReview.length}`);
console.log('Wrote reports/coverage.json and reports/coverage.md');
